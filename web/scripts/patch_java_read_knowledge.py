# 各 ### 读程 XX 题
def insert_kp(match):
    title = match.group(1)  # e.g. "读程 A1" or "读程 A6（PPT UnmaskField 原版）"
    key = re.match(r"(读程 [A-H]\d+)", title)
    if not key:
        return match.group(0)
    k = key.group(1)
    if k not in KP:
        return match.group(0)
    block = match.group(0)
    if "**📖 相关知识点**" in block:
        return block
    # 在标题后、空行、```java 前插入
    return f"### {title}\n\n{KP[k]}\n```java"


