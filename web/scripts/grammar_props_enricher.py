def _normalize_key(name):
    """「に」 / ～ことにする / 样态そう → lookup key"""
    n = name.strip()
    if n in ALIASES:
        return ALIASES[n]
    bare = n.strip("「」")
    if bare in PARTICLE:
        return bare
    if n in PARTICLE or n in DETAILED:
        return n
    for k in DETAILED:
        if bare in k or k.strip("～") == bare:
            return k
    return n

def enrich_props(name, meaning, conn, short_props, notes=""):
    """Return list of (title, body) for 文法的性质."""
    key = _normalize_key(name)

    if key in PARTICLE:
        return PARTICLE[key]
    if key in DETAILED:
        return DETAILED[key]

    cat = CATEGORY.get(key) or CATEGORY.get(name)
    if cat and cat in TPL_MAP:
        return TPL_MAP[cat](name, meaning, conn, short_props, notes)

    # ので special in category
    if "ので" in name or name == "～ので":
        return _tpl_cause_objective(name, meaning, conn, short_props, notes)

    return _tpl_generic(name, meaning, conn, short_props, notes)
