"""Expand 文法的性质 into detailed multi-section explanations."""

def _sec(title, body):
    return (title, body.strip())

def format_props(props):
    """Render props: str | (title, body) | list of either."""
    lines = []
    n = 0
    for p in props:
        if isinstance(p, (tuple, list)) and len(p) == 2 and isinstance(p[0], str) and isinstance(p[1], str) and len(p[0]) < 40:
            n += 1
            lines.append(f"#### {n}. {p[0]}\n\n{p[1]}\n")
        else:
            n += 1
            lines.append(f"{n}. {p}\n")
    return "\n".join(lines)

