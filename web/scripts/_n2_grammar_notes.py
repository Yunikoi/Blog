_n("数量＋に（达到）", """
**核心义**：数量词后接助词 **に**，表示数量「达到」某一水平，与移动、达成类动词搭配。

**接续**：数量词（数字+量词）＋ **に** ＋ 上る／達する／及ぶ 等

**用法详解**
- 「に上る」= 达到（人数、金额、规模），书面、新闻常见
- 「に達する」= 达到（标准、数值）
- 助词对比：**で**=方式/原因；**を**=宾语；**も**=「也/竟有」强调数量之多

**例句**
1. 入場者数は1000万人**に上った**。（入场人数达到了1000万）
2. 売上高が昨年**に達した**。（销售额达到了去年水平）
3. 被害者は100人**を超えた**。（受害者超过了100人）← 超える前用「を」

**近义辨析**
| 助词 | 功能 | 典型动词 |
|------|------|----------|
| に | 达到某数量点 | 上る、達する |
| を | 越过/超过 | 超える |
| で | 方式、原因 | — |

**真题提示（2015.07 第33题）**：`1000万人（ ）上った` → 选 **に**。看到「数字+上る/達する」几乎固定 **に**。
""")

_n("をめぐる／の末", """
**核心义**
- **をめぐって／をめぐり**：围绕……（话题、争议、讨论）
- **の末（に）**：经过（长期努力、讨论、斗争）之后，终于……

**接续**
- 名詞＋をめぐって（をめぐり）
- 名詞＋の末（に）

**用法详解**
- 「をめぐって」后接：議論する、争う、意見が分かれる、話し合い
- 「の末に」前接：長期間の〜、苦労の〜、議論の〜；后接：決定した、結論が出た
- **を込めて**：带着（心情）做……——强调「心意」，不是「经过过程」

**例句**
1. 新駅建設**をめぐって**、住民と鉄道会社が対立している。
2. 長期間の議論**の末に**、計画が承認された。
3. 祈り**を込めて**花を供えた。

**近义辨析**
| 表达 | 关键词 | 后项 |
|------|--------|------|
| をめぐって | 围绕、关于 | 讨论/对立 |
| の末に | 经过…之后 | 决定/结果 |
| を込めて | 带着…心情 | 动作 |

**真题提示**：选项常四者齐出（をめぐり／を込めて／の末に／のことで）。**议论+最终决定** → の末に；**围绕某议题** → をめぐって。
""")

