DEFAULT_NOTE = """
**说明**：该考点在真题中出现次数较少，请结合下方 **分套真题** 中对应题目的题干与选项复习。

**复习建议**：查词典确认接续 → 造一个例句 → 与形近语法对比。
""".strip()


def explain(tag: str) -> tuple[str, str, str, str]:
    """兼容旧接口：返回 (摘要, 全文, 例句行, 提示行) 供分套题用。"""
    key = ALIASES.get(tag, tag)
    body = NOTES.get(key, DEFAULT_NOTE)
    lines = [ln.strip() for ln in body.splitlines() if ln.strip()]
    summary = lines[0].replace("**核心义**：", "").replace("**核心义**", "").strip("：: ")
    if summary.startswith("**"):
        summary = summary.strip("*").split("**")[0]
    # 提取例句段
    example = "—"
    tip = "—"
    in_ex = in_tip = False
    ex_lines: list[str] = []
    for ln in lines:
        if "例句" in ln and ln.startswith("**"):
            in_ex, in_tip = True, False
            continue
        if ("辨析" in ln or "真题" in ln or "提示" in ln) and ln.startswith("**"):
            in_ex, in_tip = False, True
            if "真题" in ln or "提示" in ln:
                tip = ln.replace("**", "")
            continue
        if in_ex and ln and not ln.startswith("|"):
            ex_lines.append(ln)
        if in_tip and ln and not ln.startswith("|"):
            tip = (tip + " " + ln) if tip != "—" else ln
    if ex_lines:
        example = ex_lines[0].lstrip("0123456789. ")
    return summary[:120], body, example, tip[:200]


def explain_body(tag: str) -> str:
    key = ALIASES.get(tag, tag)
    return NOTES.get(key, DEFAULT_NOTE)
