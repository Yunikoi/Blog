_n("〜もの", """
**核心义**：形式名词「もの」，N2 常考四种固定句型，**必须按后接形式区分**。

**主要句型**

| 句型 | 义 | 接续 |
|------|-----|------|
| **ものだ** | 一般性道理、感慨 | 普通形＋ものだ |
| **ものではない** | 不应该（规劝） | 辞书形＋ものではない |
| **ものの** | 虽然……但是…… | 普通形＋ものの |
| **ものなら** | 如果可能的话…… | 辞书形＋ものなら |

**用法详解**
- **ものだ**：「子供は元気な**ものだ**」= 孩子嘛，就是活泼（说话人感慨、一般真理）
- **ものではない**：「約束を破る**ものではない**」= 不该违约（社会规范）
- **ものの**：前项成立，后项却未如愿；比「のに」稍书面
- **ものなら**：与「〜たい」连用，表「要是能……就好了（但做不到）」

**例句**
1. 人生は思い通りにならない**ものだ**。
2. 人の悪口を言う**ものではない**。
3. 行きたい**ものの**、時間がなくて行けなかった。
4. 行ける**ものなら**、今すぐ行きたい。

**近义辨析**
| | ものだ | はずだ | べきだ |
|---|--------|--------|--------|
| 类型 | 感慨/常理 | 理应如此 | 应该做 |

**真题提示**：选项四者齐出（ものだ／ものではない／ものの／ものなら）时，看 **后项语气**：规劝→ではない；转折→ものの；假设→なら。
""")

