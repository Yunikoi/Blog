def lesson_header(n, title, desc, forms):
    forms_str = " · ".join(forms)
    return f"""
## 第{n}课　{title}

> **本课定位**：{desc}  
> **本课文法**：{forms_str}  
> **学法（新完全式）**：逐条读 **意味→接续→文法性质→例句** → 最后看 **本课辨析表** 自己说出差别。

"""

def lesson_principle(text):
    return f"\n### 本课原理\n\n{text}\n"

def form(num, name, meaning, conn, props, examples, notes="", compare="", flow="", contrast="", detailed=True):
    if detailed:
        rich = enrich_props(name, meaning, conn, props, notes)
        props_txt = format_props(rich)
    else:
        props_txt = format_props(props)
    ex_txt = "\n".join(f"   - {e}" for e in examples)
    s = f"""
### 文法形式{num}　{name}

**意味**：{meaning}

**接续**：{conn}

**文法的性质**：

{props_txt}

**例句**：

{ex_txt}
"""
    if flow:
        s += f"\n**判断流程**：{flow}\n"
    if contrast:
        s += f"\n**同境对比**：{contrast}\n"
    if notes:
        s += f"\n**注意／限制**：{notes}\n"
    if compare:
        s += f"\n**与同课文法对比**：{compare}\n"
    return s

def form_from_tuple(num, item):
    name, meaning, conn, props, examples, notes = item
    return form(num, name, meaning, conn, props, examples, notes)

def lesson_table(rows):
    lines = ["\n### 本课辨析（课末总表）\n", "| 文法 | 接续 | 核心差别一句 | 后项／语气限制 |", "|------|------|--------------|----------------|"]
    for r in rows:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} |")
    return "\n".join(lines) + "\n"

